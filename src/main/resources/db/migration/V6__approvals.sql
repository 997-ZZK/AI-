-- 人工审批节点：挂起 / 恢复所需的持久化（设计见 docs/approval-node-design.md）。
--
-- 三张表各解决一件事：
--   approvals       —— 待办本体：谁该批、批没批、什么时候到期、策略是什么
--   approval_events —— 追加型流水：谁在什么时候做了什么（approvals 一行只有最终状态，过程信息丢了找不回来）
--   run_checkpoints —— 断点：从哪儿、以什么状态继续跑
--
-- 为什么 policy 进 approvals（而不是每次去读工作流节点参数）：
--   ① 语义上，审批一旦发出规则就该冻结 —— 改工作流不该改变一个"已经在等"的审批怎么超时；
--   ② 结构上，超时扫描读节点参数得走 WorkflowService -> GraphValidator -> NodeRegistry，
--      而那条路依赖执行器、执行器又依赖审批服务，会绕成环。
--
-- 为什么 (run_id, node_id, level) 唯一：一层一行、升级换行。同一层重复落单只可能是 bug 或重试，
-- 让数据库直接拦住（审批节点在装配期已经禁止配 retry，这是第二道闸）。
--
-- 为什么 run_checkpoints 是 append：一次运行可能挂起多次（两道审批），
-- 留成多行才能回答"恢复时用的是哪一份快照"，consumed_at 标出它有没有被用过。
create table approvals (
    id uuid primary key,
    run_id uuid not null references workflow_runs (id),
    node_id varchar(64) not null,
    level integer not null default 1,
    status varchar(24) not null,
    title varchar(2000),
    detail varchar(8000),
    assignees varchar(512) not null,
    policy jsonb not null,
    decision varchar(24),
    decided_by varchar(128),
    decided_at timestamptz,
    comment varchar(2000),
    due_at timestamptz not null,
    created_at timestamptz not null,
    updated_at timestamptz not null
);
create unique index uq_approvals_level on approvals (run_id, node_id, level);
create index idx_approvals_due on approvals (status, due_at);
create index idx_approvals_run on approvals (run_id, created_at);

create table approval_events (
    id bigint generated by default as identity primary key,
    approval_id uuid not null references approvals (id) on delete cascade,
    event varchar(32) not null,
    actor varchar(128),
    comment varchar(2000),
    detail jsonb,
    created_at timestamptz not null
);
create index idx_approval_events_approval on approval_events (approval_id, created_at);

create table run_checkpoints (
    id uuid primary key,
    run_id uuid not null references workflow_runs (id) on delete cascade,
    node_id varchar(64) not null,
    seq integer not null,
    state jsonb not null,
    created_at timestamptz not null,
    consumed_at timestamptz
);
create index idx_run_checkpoints_run on run_checkpoints (run_id, seq);

-- 挂起时记下在等哪个节点；终态与恢复时清空。
-- 不加外键：它只是个诊断/查询字段，指向 node_runs 的一行会引入"节点行先删"的耦合。
alter table workflow_runs add column waiting_node_id varchar(64);

comment on table approvals is '人工审批待办与层级历史（level 升级会新增一行，旧的留成 EXPIRED）';
comment on column approvals.policy is '请求时刻的策略快照：onTimeout / maxLevel / onExhausted / escalateAssignees / onReject / fallback / waitSeconds';
comment on column approvals.assignees is '审批人名单，逗号分隔；any 表示不限（⚠️ 当前无鉴权，名单不是安全边界）';
comment on table approval_events is '审批流水（追加型）：REQUESTED / APPROVED / REJECTED / EXPIRED / CANCELED';
comment on table run_checkpoints is '运行检查点：挂起后从哪儿、以什么状态继续；consumed_at 非空表示已被用掉';
comment on column workflow_runs.waiting_node_id is '挂起时在等哪个节点；非挂起状态为 null';
