package com.aiflow.engine.persistence.entity;

import com.aiflow.engine.session.DispatchKind;
import com.aiflow.engine.session.DispatchStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import org.hibernate.annotations.Immutable;

import java.time.Instant;
import java.util.UUID;

/** Read model. PgDispatchTaskStore owns all conditional state transitions. */
@Entity
@Immutable
@Table(name = "session_dispatch_tasks")
public class DispatchTaskEntity {
    @Id
    private UUID id;

    @Column(name = "session_id", nullable = false)
    private UUID sessionId;

    @Column(name = "run_id", nullable = false)
    private UUID runId;

    @Column(nullable = false, unique = true, insertable = false, updatable = false,
            columnDefinition = "bigint generated by default as identity")
    private long seq;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private DispatchKind kind;

    @Column(name = "checkpoint_id")
    private UUID checkpointId;

    @Column(name = "approval_id")
    private UUID approvalId;

    @Column(name = "dedupe_key", nullable = false, unique = true, length = 96)
    private String dedupeKey;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 16)
    private DispatchStatus status;

    @Column(name = "owner_token", length = 36)
    private String ownerToken;

    @Column(name = "lease_until")
    private Instant leaseUntil;

    @Column(name = "cancel_requested_at")
    private Instant cancelRequestedAt;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    @Column(name = "started_at")
    private Instant startedAt;

    @Column(name = "finished_at")
    private Instant finishedAt;

    @Column(name = "last_error", length = 4000)
    private String lastError;

    public UUID getId() { return id; }
    public UUID getSessionId() { return sessionId; }
    public UUID getRunId() { return runId; }
    public long getSeq() { return seq; }
    public DispatchKind getKind() { return kind; }
    public UUID getCheckpointId() { return checkpointId; }
    public UUID getApprovalId() { return approvalId; }
    public String getDedupeKey() { return dedupeKey; }
    public DispatchStatus getStatus() { return status; }
    public String getOwnerToken() { return ownerToken; }
    public Instant getLeaseUntil() { return leaseUntil; }
    public Instant getCancelRequestedAt() { return cancelRequestedAt; }
    public Instant getCreatedAt() { return createdAt; }
    public Instant getUpdatedAt() { return updatedAt; }
    public Instant getStartedAt() { return startedAt; }
    public Instant getFinishedAt() { return finishedAt; }
    public String getLastError() { return lastError; }
}
